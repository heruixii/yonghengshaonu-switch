def ctrl_count(text: str, token: str) -> int:
    return text.count(token)


def main() -> int:
    with SOURCE.open("r", encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    keys = {(r["scene"], int(r["ns_filtered_index"])) for r in rows}
    if keys != set(T):
        missing = sorted(keys - set(T))
        extra = sorted(set(T) - keys)
        raise ValueError(f"translation key mismatch: missing={missing} extra={extra}")

    out = []
    for r in rows:
        key = (r["scene"], int(r["ns_filtered_index"]))
        source = r["ns_source"]
        translation = T[key]
        sv = VOICE_RE.match(source)
        tv = VOICE_RE.match(translation)
        if (sv.group(1) if sv else None) != (tv.group(1) if tv else None):
            raise ValueError(f"voice prefix mismatch {key}: {source!r} -> {translation!r}")
        for token in ("@k", "@n", "@p"):
            if ctrl_count(source, token) != ctrl_count(translation, token):
                raise ValueError(f"control mismatch {token} at {key}")
        if source.count("@r") != translation.count("@r"):
            raise ValueError(f"ruby count mismatch at {key}")
        out.append({**r, "translation": translation})

    fields = list(rows[0].keys()) + ["translation"]
    with OUTPUT.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, delimiter="\t", lineterminator="\n")
        w.writeheader(); w.writerows(out)
    print(f"rows={len(out)}")
    print(f"output={OUTPUT}")
    return 0


