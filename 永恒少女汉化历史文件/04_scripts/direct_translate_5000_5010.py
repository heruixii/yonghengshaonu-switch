def main() -> int:
    with SOURCE.open("r", encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    keys = {(r["scene"], int(r["ns_filtered_index"])) for r in rows}
    if keys != set(T):
        raise ValueError(f"key mismatch missing={sorted(keys-set(T))} extra={sorted(set(T)-keys)}")
    out = []
    for r in rows:
        key = (r["scene"], int(r["ns_filtered_index"]))
        source, translation = r["ns_source"], T[key]
        sv, tv = VOICE_RE.match(source), VOICE_RE.match(translation)
        if (sv.group(1) if sv else None) != (tv.group(1) if tv else None):
            raise ValueError(f"voice mismatch {key}")
        if STRICT_RE.findall(source) != STRICT_RE.findall(translation):
            raise ValueError(f"strict control mismatch {key}")
        if source.count("@n") != translation.count("@n"):
            raise ValueError(f"@n mismatch {key}")
        if KANA_RE.search(translation):
            raise ValueError(f"kana residue {key}: {translation}")
        out.append({**r, "translation": translation})
    fields = list(rows[0].keys()) + ["translation"]
    with OUTPUT.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, delimiter="\t", lineterminator="\n")
        w.writeheader(); w.writerows(out)
    print(f"rows={len(out)}")
    print(f"output={OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
